CREATE SCHEMA baynet;
REVOKE ALL ON SCHEMA baynet FROM PUBLIC;

CREATE TABLE baynet.settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE baynet.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL, division TEXT NOT NULL, role TEXT NOT NULL,
  review_divisions TEXT NOT NULL DEFAULT '[]', password_hash TEXT NOT NULL
);
CREATE TABLE baynet.sessions (
  token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES baynet.users(id), expires BIGINT NOT NULL
);
CREATE TABLE baynet.reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id INTEGER NOT NULL REFERENCES baynet.users(id),
  date TEXT NOT NULL, shift TEXT NOT NULL CHECK(shift IN ('Pagi','Siang')),
  slot TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'draft',
  activities TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL, UNIQUE(author_id, date, slot)
);
CREATE INDEX reports_date ON baynet.reports(date, status);
CREATE TABLE baynet.history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id INTEGER NOT NULL REFERENCES baynet.reports(id) ON DELETE CASCADE,
  status TEXT NOT NULL, actor_id INTEGER NOT NULL REFERENCES baynet.users(id), note TEXT NOT NULL, at TEXT NOT NULL
);
CREATE INDEX history_report ON baynet.history(report_id);
CREATE TABLE baynet.attachments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id INTEGER NOT NULL REFERENCES baynet.reports(id) ON DELETE CASCADE,
  name TEXT NOT NULL, mime TEXT NOT NULL, size INTEGER NOT NULL, content BYTEA NOT NULL
);
CREATE INDEX attachments_report ON baynet.attachments(report_id);
